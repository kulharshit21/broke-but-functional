/**
 * Financial domain model and TypeScript interfaces for Broke But Functional.
 * Uses integer paise representation internally to eliminate floating-point arithmetic errors.
 */

/**
 * Standard expense and allocation categories.
 */
export type Category =
  | "needs"
  | "groceries"
  | "food"
  | "transport"
  | "subscriptions"
  | "utilities"
  | "fun"
  | "social"
  | "health"
  | "education"
  | "emergency"
  | "income"
  | "savings"
  | "debt";

/**
 * Transaction operational types.
 */
export type TransactionType =
  | "income"
  | "expense"
  | "savings_contribution"
  | "goal_withdrawal"
  | "subscription_charge"
  | "commitment_payment"
  | "emergency"
  | "loan_received"
  | "loan_repayment";

/**
 * Ledger transaction representation.
 */
export interface Transaction {
  id: string;
  label: string;
  amount: number;
  day: number;
  category: Category;
  type: TransactionType;
  status: "completed" | "upcoming";
  essential: boolean;
  note?: string;
}

/**
 * Scheduled fixed liability or commitment due within the month.
 */
export interface Commitment {
  id: string;
  label: string;
  amount: number;
  day: number;
  category: Category;
  essential: boolean;
  status: "upcoming" | "paid";
  optional?: boolean;
}

/**
 * Recurring monthly subscription entry.
 */
export interface Subscription {
  id: string;
  label: string;
  amount: number;
  day: number;
  category: Category;
  status: "active" | "paused" | "cancelled";
}

/**
 * Targeted savings milestone goal.
 */
export interface Goal {
  id: string;
  label: string;
  target: number;
  saved: number;
  protected: boolean;
  targetDay: number;
  plannedContribution: number;
  note: string;
}

/**
 * Probabilistic financial shock or emergency risk factor.
 */
export interface Risk {
  id: string;
  label: string;
  amount: number;
  probability: number;
  day: number;
  active: boolean;
}

/**
 * Immutable audit log of deliberate financial actions.
 */
export interface DecisionLog {
  id: string;
  label: string;
  day: number;
  consequence: string;
}

/**
 * User financial configuration profile.
 */
export interface Profile {
  monthLength: number;
  currentDay: number;
  startingBalance: number;
  minimumBuffer: number;
  plannedDailySpend: number;
  riskTolerance: "cautious" | "balanced" | "bold";
}

/**
 * Complete root domain state representation.
 */
export interface MoneyState {
  version: 1;
  profile: Profile;
  ledger: Transaction[];
  commitments: Commitment[];
  subscriptions: Subscription[];
  goals: Goal[];
  risks: Risk[];
  decisionsLog: DecisionLog[];
}

/**
 * Kinds of what-if scenarios that can be tested in the simulation lab.
 */
export type ScenarioKind =
  | "expense"
  | "income"
  | "pause_subscription"
  | "cancel_subscription"
  | "savings"
  | "withdraw_savings"
  | "delay_bill"
  | "bnpl"
  | "side_gig"
  | "emergency";

/**
 * Simulation scenario specification.
 */
export interface Scenario {
  id: string;
  label: string;
  kind: ScenarioKind;
  amount: number;
  day: number;
  category: Category;
  targetId?: string;
  secondaryAmount?: number;
  includeShocks?: boolean;
}

/**
 * Single-day cashflow forecast model across the 30-day timeline.
 */
export interface ForecastDay {
  day: number;
  balance: number;
  committedOutflow: number;
  income: number;
  discretionary: number;
  scenarioImpact: number;
  isDanger: boolean;
  isLow: boolean;
  events: string[];
}

/**
 * Core synthesized financial metrics and risk indices.
 */
export interface Metrics {
  currentBalance: number;
  daysLeft: number;
  committed: number;
  protectedSavings: number;
  expectedShock: number;
  shockReserve: number;
  safeDaily: number;
  monthEnd: number;
  minimumProjected: number;
  runway: number;
  dangerDays: number;
  nextDangerDay: number | null;
  riskScore: number;
  riskLabel: string;
  healthScore: number;
  healthLabel: string;
}

/**
 * Consequence impact assessment on active savings targets.
 */
export interface GoalImpact {
  goalId: string;
  goalName: string;
  stillOnTrack: boolean;
  delayDays: number;
  dailyRequired: number;
}

/**
 * Category-level breakdown item for spending distribution.
 */
export interface CategoryBreakdownItem {
  category: Category;
  name: string;
  amount: number;
  percentage: number;
  color: string;
}

/**
 * Personalized runway intelligence and financial guidance item.
 */
export interface RunwayAdviceItem {
  id: string;
  type: "warning" | "opportunity" | "tip" | "success";
  title: string;
  message: string;
  actionable?: string;
}

/**
 * Complete consequence result generated by the simulation engine.
 */
export interface SimulationResult {
  before: Metrics;
  after: Metrics;
  baseline: ForecastDay[];
  scenarioForecast: ForecastDay[];
  warnings: string[];
  recommendation: string;
  story: string;
  goalImpact?: GoalImpact[];
}
